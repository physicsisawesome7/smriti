# Smriti one-click installer for Windows (Docker Desktop with the WSL2 backend).
#
#   powershell -ExecutionPolicy Bypass -File install.ps1
#   .\install.ps1 -Profile gpu-12gb        cpu | gpu-6gb | gpu-12gb | gpu-16gb | gpu-24gb
#   .\install.ps1 -Reconfigure             rewrite .env from the profile (old one kept as .env.bak)
#   .\install.ps1 -Status | -Stop | -Uninstall
#
# Re-running is safe: an existing .env is kept, so your edits survive upgrades.
param(
    [Alias("Profile")][string]$Tier = "",
    [switch]$Reconfigure,
    [switch]$Status,
    [switch]$Stop,
    [switch]$Uninstall
)
# Native tools (docker) write progress and warnings to stderr; Windows PowerShell 5.1
# would turn those into terminating errors under "Stop". Failures are checked through
# $LASTEXITCODE instead.
$ErrorActionPreference = "Continue"
Set-Location -Path $PSScriptRoot

function Say($m) { Write-Host "> $m" -ForegroundColor Magenta }
function Die($m) { Write-Host "x $m" -ForegroundColor Red; exit 1 }

if (-not (Get-Command docker -ErrorAction SilentlyContinue)) { Die "Docker Desktop is not installed: https://docs.docker.com/desktop/setup/install/windows-install/" }

# Start Docker Desktop if needed and wait for the engine
cmd /c "docker info >nul 2>&1"
if ($LASTEXITCODE -ne 0) {
    $dd = Join-Path $Env:ProgramFiles "Docker\Docker\Docker Desktop.exe"
    if (Test-Path $dd) { Say "starting Docker Desktop..."; Start-Process $dd }
    $ok = $false
    for ($i = 0; $i -lt 60; $i++) { Start-Sleep 5; cmd /c "docker info >nul 2>&1"; if ($LASTEXITCODE -eq 0) { $ok = $true; break } }
    if (-not $ok) { Die "Docker is not running. Start Docker Desktop and run this again." }
}

if ($Status) { docker compose ps; exit 0 }
if ($Stop) { docker compose stop; exit 0 }
if ($Uninstall) {
    $a = Read-Host "Remove containers AND all data volumes (documents, index, model cache)? [y/N]"
    if ($a -eq "y") { docker compose down -v } else { docker compose down }
    exit 0
}

# ---- hardware detection ------------------------------------------------------------
$vram = 0; $cc = ""; $gpu = "none"
if (Get-Command nvidia-smi -ErrorAction SilentlyContinue) {
    $line = (nvidia-smi --query-gpu=name,memory.total,compute_cap --format=csv,noheader,nounits | Select-Object -First 1)
    if ($line) {
        $parts = $line.Split(",") | ForEach-Object { $_.Trim() }
        $gpu = $parts[0]; $vram = [int]$parts[1]; $cc = $parts[2]
    }
}
$ramGb = [math]::Round((Get-CimInstance Win32_ComputerSystem).TotalPhysicalMemory / 1GB)
Say "GPU: $gpu ($vram MiB, compute $cc)   RAM: $ramGb GB"

if (-not $Tier) {
    if ($vram -ge 22000) { $Tier = "gpu-24gb" }
    elseif ($vram -ge 15000) { $Tier = "gpu-16gb" }
    elseif ($vram -ge 11000) { $Tier = "gpu-12gb" }
    elseif ($vram -ge 5500) { $Tier = "gpu-6gb" }
    else { $Tier = "cpu" }
}
$profileFile = "deploy/profiles/$Tier.env"
if (-not (Test-Path $profileFile)) { Die "no profile $profileFile" }

if ($Tier -ne "cpu") {
    Say "checking that containers can see the GPU..."
    cmd /c "docker run --rm --gpus all ubuntu:24.04 nvidia-smi -L >nul 2>&1"
    if ($LASTEXITCODE -ne 0) { Die "containers cannot use the GPU. Update the NVIDIA driver and Docker Desktop (WSL2 backend), or run with -Profile cpu" }
}

$tei = switch -Regex ($cc) {
    "^7\.5$" { "turing-1.9" }
    "^8\.0$" { "1.9" }
    "^8\.[67]$" { "86-1.9" }
    "^8\.9$" { "89-1.9" }
    "^9\.0$" { "hopper-1.9" }
    "^12\." { "120-1.9" }
    default { "cpu-1.9" }
}

# ---- .env ---------------------------------------------------------------------------
if ((Test-Path .env) -and -not $Reconfigure) {
    Say "keeping existing .env (use -Reconfigure to regenerate from profile '$Tier')"
} else {
    if (Test-Path .env) { Copy-Item .env .env.bak -Force; Say "previous .env saved as .env.bak" }
    $vals = [ordered]@{}
    foreach ($f in @("deploy/profiles/_common.env", $profileFile)) {
        foreach ($l in Get-Content $f) {
            if ($l -match '^([A-Za-z_][A-Za-z0-9_]*)=(.*)$') { $vals[$Matches[1]] = $l }
        }
    }
    # Postgres keeps the password it was initialised with; reuse it so a reconfigure never locks out the data
    $pg = ""
    if (Test-Path .env.bak) { $pg = ((Get-Content .env.bak | Where-Object { $_ -match '^POSTGRES_PASSWORD=' }) -replace '^POSTGRES_PASSWORD=', '') }
    if (-not $pg) { $pg = -join ((48..57) + (65..90) + (97..122) | Get-Random -Count 24 | ForEach-Object { [char]$_ }) }
    $lines = @("# generated by install.ps1 on $(Get-Date -Format s) for $gpu ($vram MiB)") + $vals.Values
    $lines += "TEI_IMAGE=ghcr.io/huggingface/text-embeddings-inference:$tei"
    $lines += "POSTGRES_PASSWORD=$pg"
    [System.IO.File]::WriteAllLines((Join-Path $PSScriptRoot ".env"), $lines, (New-Object System.Text.UTF8Encoding($false)))
    Say "wrote .env for profile '$Tier'"
}

# ---- start ---------------------------------------------------------------------------
Say "building and starting (first run downloads images and models: several GB)..."
docker compose up -d --build
if ($LASTEXITCODE -ne 0) { Die "docker compose up failed" }

$port = ((Get-Content .env | Where-Object { $_ -match '^SMRITI_PORT=' }) -replace 'SMRITI_PORT=', '')
if (-not $port) { $port = "8000" }
Say "waiting for Smriti and the model servers (first start can take 10-30 min)..."
for ($i = 1; $i -le 360; $i++) {
    try {
        $r = Invoke-WebRequest -UseBasicParsing -TimeoutSec 5 "http://127.0.0.1:$port/api/health?deep=1"
        if ($r.StatusCode -eq 200) {
            Say "ready: http://127.0.0.1:$port"
            Write-Host "  benchmark:  docker compose exec smriti-api smriti bench --url http://127.0.0.1:8000"
            Write-Host "  logs:       docker compose logs -f llm smriti-api"
            Write-Host "  customise:  edit .env or packs\, then docker compose up -d"
            Start-Process "http://127.0.0.1:$port"
            exit 0
        }
    } catch { }
    if ($i % 12 -eq 0) { docker compose ps --format "{{.Service}}: {{.Status}}" }
    Start-Sleep 5
}
Die "not ready after 30 minutes; see: docker compose logs --tail 50"
