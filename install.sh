#!/usr/bin/env bash
# Smriti one-click installer (Linux, WSL2, macOS).
#
#   ./install.sh                      detect the GPU, write .env, start, wait until ready
#   ./install.sh --profile gpu-12gb   force a profile: cpu | gpu-6gb | gpu-12gb | gpu-16gb | gpu-24gb
#   ./install.sh --reconfigure        rewrite .env from the profile (your old one is kept as .env.bak)
#   ./install.sh --status | --stop | --uninstall
#
# Re-running is safe: an existing .env is kept, so your edits survive upgrades.
set -euo pipefail
cd "$(dirname "$0")"

PROFILE="" RECONFIGURE=0 ACTION=install
while [[ $# -gt 0 ]]; do
  case "$1" in
    --profile) PROFILE="$2"; shift 2 ;;
    --reconfigure) RECONFIGURE=1; shift ;;
    --status) ACTION=status; shift ;;
    --stop) ACTION=stop; shift ;;
    --uninstall) ACTION=uninstall; shift ;;
    -h|--help) sed -n '2,10p' "$0"; exit 0 ;;
    *) echo "unknown option $1"; exit 2 ;;
  esac
done

say() { printf '\033[1;35m▸\033[0m %s\n' "$*"; }
die() { printf '\033[1;31m✗ %s\033[0m\n' "$*" >&2; exit 1; }

command -v docker >/dev/null || die "Docker is not installed: https://docs.docker.com/engine/install/"
docker compose version >/dev/null 2>&1 || die "Docker Compose v2 is missing (docker compose ...)"
docker info >/dev/null 2>&1 || die "Docker is not running. Start Docker (Desktop) and run this again."

case "$ACTION" in
  status) docker compose ps; curl -fsS "http://127.0.0.1:$(grep -E '^SMRITI_PORT=' .env | cut -d= -f2)/api/health?deep=1" && echo; exit 0 ;;
  stop) docker compose stop; exit 0 ;;
  uninstall)
    read -r -p "Remove containers AND all data volumes (documents, index, model cache)? [y/N] " a
    [[ "$a" == "y" || "$a" == "Y" ]] && docker compose down -v || docker compose down
    exit 0 ;;
esac

# ---- hardware detection -------------------------------------------------------
VRAM_MB=0 CC="" GPU_NAME="none"
if command -v nvidia-smi >/dev/null 2>&1; then
  line=$(nvidia-smi --query-gpu=name,memory.total,compute_cap --format=csv,noheader,nounits 2>/dev/null | head -1 || true)
  if [[ -n "$line" ]]; then
    GPU_NAME=$(echo "$line" | cut -d, -f1 | xargs)
    VRAM_MB=$(echo "$line" | cut -d, -f2 | xargs)
    CC=$(echo "$line" | cut -d, -f3 | xargs)
  fi
fi
RAM_GB=$(awk '/MemTotal/ {printf "%d", $2/1024/1024}' /proc/meminfo 2>/dev/null || echo 0)
say "GPU: ${GPU_NAME} (${VRAM_MB} MiB, compute ${CC:-n/a})   RAM: ${RAM_GB} GB"

if [[ -z "$PROFILE" ]]; then
  if (( VRAM_MB >= 22000 )); then PROFILE=gpu-24gb
  elif (( VRAM_MB >= 15000 )); then PROFILE=gpu-16gb
  elif (( VRAM_MB >= 11000 )); then PROFILE=gpu-12gb
  elif (( VRAM_MB >= 5500 )); then PROFILE=gpu-6gb
  else PROFILE=cpu; fi
fi
[[ -f "deploy/profiles/$PROFILE.env" ]] || die "no profile deploy/profiles/$PROFILE.env"

if [[ "$PROFILE" != cpu ]]; then
  say "checking that containers can see the GPU (NVIDIA Container Toolkit)…"
  docker run --rm --gpus all ubuntu:24.04 nvidia-smi -L >/dev/null 2>&1 \
    || die "containers cannot use the GPU. Install the NVIDIA Container Toolkit (Linux) or enable WSL2 GPU support (Docker Desktop), or run with --profile cpu"
fi

# TEI publishes one image per GPU architecture
case "$CC" in
  7.5) TEI_TAG=turing-1.9 ;;
  8.0) TEI_TAG=1.9 ;;
  8.6|8.7) TEI_TAG=86-1.9 ;;
  8.9) TEI_TAG=89-1.9 ;;
  9.0) TEI_TAG=hopper-1.9 ;;
  12.*) TEI_TAG=120-1.9 ;;
  *) TEI_TAG=cpu-1.9 ;;
esac

# ---- .env ---------------------------------------------------------------------------
if [[ -f .env && $RECONFIGURE == 0 ]]; then
  say "keeping existing .env (use --reconfigure to regenerate from profile '$PROFILE')"
else
  [[ -f .env ]] && cp .env .env.bak && say "previous .env saved as .env.bak"
  # Postgres keeps the password it was initialised with; reuse it so a reconfigure never locks out the data
  PG_PASS=$(grep -E '^POSTGRES_PASSWORD=' .env.bak 2>/dev/null | cut -d= -f2- || true)
  [[ -n "$PG_PASS" ]] || PG_PASS=$(head -c 18 /dev/urandom | base64 | tr -dc 'A-Za-z0-9' | head -c 24)
  {
    echo "# generated by install.sh on $(date -u +%FT%TZ) for ${GPU_NAME} (${VRAM_MB} MiB)"
    # later keys win: common, then profile, then detected values
    cat deploy/profiles/_common.env deploy/profiles/"$PROFILE".env | awk -F= '
      /^[A-Za-z_][A-Za-z0-9_]*=/ { if (!($1 in seen)) order[++n]=$1; seen[$1]=$0; next }
      END { for (i=1;i<=n;i++) print seen[order[i]] }'
    echo "TEI_IMAGE=ghcr.io/huggingface/text-embeddings-inference:${TEI_TAG}"
    echo "POSTGRES_PASSWORD=${PG_PASS}"
    echo "SEARXNG_SECRET=$(head -c 24 /dev/urandom | base64 | tr -dc 'A-Za-z0-9' | head -c 32)"
  } > .env
  say "wrote .env for profile '$PROFILE'"
fi

# ---- start ---------------------------------------------------------------------------
say "building and starting (first run downloads images and models: several GB)…"
docker compose up -d --build

PORT=$(grep -E '^SMRITI_PORT=' .env | cut -d= -f2); PORT=${PORT:-8000}
say "waiting for Smriti and the model servers to be ready (first start can take 10-30 min)…"
for i in $(seq 1 360); do
  if curl -fsS "http://127.0.0.1:${PORT}/api/health?deep=1" >/dev/null 2>&1; then
    say "ready: http://127.0.0.1:${PORT}"
    echo "  benchmark:  docker compose exec smriti-api smriti bench --url http://127.0.0.1:8000"
    echo "  logs:       docker compose logs -f llm smriti-api"
    echo "  customise:  edit .env or packs/, then docker compose up -d"
    exit 0
  fi
  (( i % 12 == 0 )) && docker compose ps --format '{{.Service}}: {{.Status}}' | sed 's/^/    /'
  sleep 5
done
die "not ready after 30 minutes; see: docker compose logs --tail 50"
